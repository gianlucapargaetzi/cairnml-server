# Views for the template


@dataclass
class Prop:
    name: str  # the Python attribute
    hint: str
    required: bool
    setter: List[str]
    wire: str = ""  # the name in the JSON, when it is not a Python identifier (for example "input.view.dataset")
    constant: Optional[str] = None  # the Python literal of a read-only property (a single-value enumeration)

    @property
    def annotation(self) -> str:
        return self.hint if self.required or self.hint == "Any" else f"Optional[{self.hint}]"


def _clean(text) -> str:
    text = " ".join(str(text).split())
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _nullable(schema: dict) -> dict:
    """Responses and data models accept null for every property the server may leave out."""
    result = dict(schema)
    if "properties" in result:
        properties = {}
        for key, prop in result["properties"].items():
            prop = dict(prop)
            if "$ref" in prop:
                ref = prop.pop("$ref")
                prop["oneOf"] = [{"$ref": ref}, {"type": "null"}]
            elif isinstance(prop.get("type"), str):
                prop["type"] = [prop["type"], "null"]
            properties[key] = prop
        result["properties"] = properties
    return result


def _identifiers(fields: dict, where: str) -> dict:
    """The Python name of each JSON field: the name itself, with the characters that cannot be in an identifier
    replaced by underscores (a schema key such as "input.view.dataset" keeps its JSON name in schema_property)."""
    names = {}
    for field_name in fields:
        python = re.sub(r"\W", "_", field_name)
        if python[:1].isdigit():
            python = "_" + python
        if keyword.iskeyword(python):
            raise Unsupported(f"{where}: the field name {field_name!r} is a Python keyword")
        if python in names.values():
            raise Unsupported(f"{where}: the field name {field_name!r} gives the Python name {python!r} twice")
        names[field_name] = python
    return names


def _constant(schema: dict) -> Optional[str]:
    """The Python literal of a property that is a single-value enumeration (a type constant), or None. Such a property
    is read-only: its value is the constant, and it is not an argument of the constructor."""
    values = schema.get("enum")
    if isinstance(values, list) and len(values) == 1 and isinstance(values[0], str):
        return _inline(values[0])
    return None


def _build_class(*, name, base, description, fields, required, schema, definitions, where, extra=None, item=None):
    """A class of fields. `item` is (name, kind, description) of the item of a compound request: a required first
    argument of the constructor that is not a field of the schema."""
    kinds = {}
    constants = {}
    descriptions = {}
    for field_name, field_schema in fields.items():
        kinds[field_name] = kind_of(field_schema, definitions, f"{where}.{field_name}")
        constants[field_name] = _constant(field_schema)
        descriptions[field_name] = field_schema.get("description", "")
    python = _identifiers(fields, where)
    names = list(fields)
    required = set(required)
    if item is not None:
        item_name, item_kind, item_description = item
        if item_name in fields:
            raise Unsupported(f"{where}: the item {item_name!r} is also a field of the request")
        names.insert(0, item_name)
        required.add(item_name)
        kinds[item_name] = item_kind
        constants[item_name] = None
        descriptions[item_name] = item_description
        python[item_name] = item_name
    ordered = [n for n in names if n in required] + [n for n in names if n not in required]
    props = [
        Prop(
            python[n],
            kinds[n].hint,
            n in required,
            _setter_lines(n, kinds[n]),
            wire=n if python[n] != n else "",
            constant=constants[n],
        )
        for n in ordered
    ]
    order = [n for n in ordered if constants[n] is None]
    params = []
    for n in order:
        if n in required:
            params.append(f"{python[n]}: {kinds[n].hint}")
        else:
            default = fields[n].get("default")
            if isinstance(default, (list, dict)):
                raise Unsupported(f"{where}.{n}: a list or object default is not supported (mutable default)")
            hint = kinds[n].hint
            params.append(f"{python[n]}: {hint if hint == 'Any' else f'Optional[{hint}]'} = {_inline(default)}")
    params.append("**kwargs: Any")
    one_line = f"    def __init__(self, {', '.join(params)}) -> None:"
    if len(one_line) <= LINE_WIDTH:
        signature = one_line
    else:
        signature = "    def __init__(\n        self,\n" + "".join(f"        {p},\n" for p in params[:-1])
        signature += "        **kwargs: Any\n    ) -> None:"
    doc = [_clean(description)] if description else []
    params_doc = []
    for n in order:
        text = _clean(descriptions[n])
        params_doc.append(f":param {python[n]}: {text}".rstrip())
        params_doc.append(f":type {python[n]}: {kinds[n].doc}")
    return {
        "name": name,
        "base": base,
        "doc": doc,
        "params_doc": params_doc,
        "schema": literal(schema, 4, "_schema = "),
        "signature": signature,
        "props": props,
        "order": [python[n] for n in order],
        "extra": extra,
        "item": item[0] if item is not None else None,
        "batched": None,
        "map": None,
    }


def _map_class(def_name: str, definition: dict, definitions: dict, where: str) -> dict:
    """A dict class of the values of a map definition: each value is converted to the item class when it is a dict."""
    item = _converted_values(definition, definitions, where, 0)
    schema = _nullable(definition)
    own = reachable_definitions([definition], definitions)
    if own:
        schema["definitions"] = {k: _nullable(v) for k, v in own.items()}
    description = definition.get("description", "")
    return {
        "name": camel(def_name),
        "base": "dict, NonStrictDataModel",
        "doc": [_clean(description)] if description else [],
        "params_doc": [],
        "schema": literal(schema, 4, "_schema = "),
        "extra": None,
        "item": None,
        "batched": None,
        "map": {"field": def_name, "item": item.cls, "convert": _construct(item, "v")},
    }


# The item of a request whose schema is a choice of shapes (anyOf or oneOf at its top level), by "service.action". The
# item is the first argument of the request's constructor, and the body the item merged with the request's own options.
# A request of several shapes that is not listed here is a generation error: the name is not guessed.
COMPOUND_ITEM_NAMES = {
    "events.add": "event",
}


def _compound_item(action: Action, definitions: dict):
    """(name, kind, description) of the item of a compound request, or None for a request of one shape."""
    request = action.request
    shapes = request.get("anyOf") or request.get("oneOf")
    if not shapes:
        return None
    name = COMPOUND_ITEM_NAMES.get(action.full_name)
    if name is None:
        raise Unsupported(f"{action.full_name}: a request of several shapes needs its item name in COMPOUND_ITEM_NAMES")
    classes = []
    for shape in shapes:
        if "$ref" not in shape:
            raise Unsupported(f"{action.full_name}: every shape of a compound request must be a definition")
        kind = kind_of(shape, definitions, f"{action.full_name}.{name}")
        if kind.name != "ref":
            raise Unsupported(f"{action.full_name}: the shape {shape['$ref']} is not an object with properties")
        classes.append(kind.cls)
    description = f"One of the shapes of the request: {', '.join(classes)}."
    return name, Kind("item", cls=", ".join(classes)), description


def _request_fields(action: Action):
    if not action.request:
        raise Unsupported(f"{action.full_name}: no `request` and no `batch_request`")
    request = action.request
    if "properties" not in request and request.get("type", "object") != "object":
        raise Unsupported(f"{action.full_name}: the request is not an object")
    return request.get("properties") or {}, set(request.get("required") or [])


def _enum_class(def_name: str, definition: dict, where: str) -> dict:
    """A class of the values of an enumeration definition; its members are named after the values."""
    members = []
    seen = set()
    for value in definition["enum"]:
        if value is None:
            continue
        python = re.sub(r"\W", "_", str(value))
        if python[:1].isdigit() or keyword.iskeyword(python):
            python = "_" + python
        if python in seen:
            raise Unsupported(f"{where}: the values of the enumeration give the member {python!r} twice")
        seen.add(python)
        members.append({"name": python, "value": _inline(value)})
    return {"name": camel(def_name), "members": members}


def _batch_class(service: Service, action: Action, meta: dict) -> dict:
    where = f"{service.name}.{action.name}"
    batched = action.batch_request.get("action")
    target = service.actions.get(batched)
    if target is None or target.batch_request:
        raise Unsupported(f"{where}: the batched action {batched!r} is not a request of this service")
    return {
        "name": camel(action.name) + "Request",
        "base": "BatchRequest",
        "doc": [_clean(action.description)] if action.description else [],
        "params_doc": [],
        "batched": camel(batched) + "Request",
        "extra": meta,
        "item": None,
        "map": None,
    }


def legacy_folder(version: str) -> str:
    """The folder of the legacy modules of one version: 2.50 -> legacy/v2_50."""
    return "v" + version.replace(".", "_")


def render_package(services, schema: Dict[str, Service]) -> str:
    """The package file of a target: `__all__` names every service of it, and a service module is imported on first
    access, so importing the package loads none of the modules. `DEFINITIONS` lists, for each action, every retained
    definition (its version and the names of its classes, oldest first) and `resolve` picks one by API version.
    `API_LEVEL` is the highest version of any definition in the schema."""
    names = sorted(services)
    definitions = []
    for name in names:
        actions = []
        for action in sorted(schema[name].history):
            blocks = schema[name].history[action]
            classes = camel(action)
            actions.append((action, [(b.version, classes + "Request", classes + "Response") for b in blocks]))
        definitions.append((name, actions))
    api_level = max(
        (block.version for service in schema.values() for blocks in service.history.values() for block in blocks),
        key=lambda v: tuple(int(part) for part in v.split(".")),
        default="",
    )
    return _env.get_template("package.py.jinja2").render(
        services=names,
        definitions=definitions,
        api_level=api_level,
        header=HEADER,
    )


def render_service_files(service: Service, session_package: str) -> Dict[str, str]:
    """The modules of one service, by their path relative to the services folder: `<service>.py` for the newest
    definitions and `legacy/v<major>_<minor>/<service>.py` for each older retained definition of a version."""
    files = {f"{service.name}.py": render_service(service, session_package)}
    legacy: Dict[str, List[Action]] = {}
    for action in sorted(service.history):
        for block in service.history[action][:-1]:
            if block.batch_request:
                raise Unsupported(
                    f"{service.name}.{action}: a batch request keeps only its newest definition in the client "
                    f"(the definition of {block.version} is not generated yet)"
                )
            legacy.setdefault(block.version, []).append(block)
    for version in sorted(legacy, key=lambda v: tuple(int(part) for part in v.split("."))):
        files[f"legacy/{legacy_folder(version)}/{service.name}.py"] = _render_module(
            service,
            session_package,
            legacy[version],
            title=f"{service.name} service, the legacy definitions first served at API version {version}",
        )
    return files


def render_service(service: Service, session_package: str) -> str:
    """The module of the newest definition of every action of the service."""
    actions = [service.actions[name] for name in sorted(service.actions)]
    return _render_module(service, session_package, actions, title=f"{service.name} service")


def _render_module(service: Service, session_package: str, actions: List[Action], title: str) -> str:
    """The module of the given definitions (one per action, all of one version)."""
    fragments = [a.request for a in actions if not a.batch_request] + [a.response for a in actions]
    for action in actions:
        if not action.batch_request:
            _request_fields(action)  # fail early with the action's name
    used = reachable_definitions(fragments, service.definitions)

    enums = []
    for def_name, definition in used.items():
        if "enum" in definition:
            enums.append(_enum_class(def_name, definition, f"{service.name}.{def_name}"))
    models = []
    for def_name, definition in used.items():
        where = f"{service.name}.{def_name}"
        if _converted_values(definition, service.definitions, where, 0) is not None:
            models.append(_map_class(def_name, definition, service.definitions, where))
            continue
        if definition.get("type") != "object" or "properties" not in definition:
            continue  # a plain type: fields that refer to it get its type
        own = reachable_definitions([definition], service.definitions)
        schema = _nullable(definition)
        if own:
            schema["definitions"] = {k: _nullable(v) for k, v in own.items()}
        models.append(
            _build_class(
                name=camel(def_name),
                base="NonStrictDataModel",
                description=definition.get("description", ""),
                fields=definition["properties"],
                required=set(),
                schema=schema,
                definitions=service.definitions,
                where=f"{service.name}.{def_name}",
            )
        )
    models.sort(key=lambda m: m["name"])

    classes = []
    batches = []
    for action in actions:
        where = f"{service.name}.{action.name}"
        meta = {"service": service.name, "action": action.name, "version": action.version}
        if action.batch_request:
            # a batch class names a request class, so it comes after all the request classes
            batches.append(_batch_class(service, action, meta))
        else:
            fields, required = _request_fields(action)
            request_defs = reachable_definitions([action.request], service.definitions)
            schema = dict(action.request)
            schema["definitions"] = request_defs
            item = _compound_item(action, service.definitions)
            classes.append(
                _build_class(
                    name=camel(action.name) + "Request",
                    base="CompoundRequest" if item is not None else "Request",
                    description=action.description,
                    fields=fields,
                    required=required,
                    schema=schema,
                    definitions=service.definitions,
                    where=where + ".request",
                    extra=meta,
                    item=item,
                )
            )
        response = action.response
        response_defs = reachable_definitions([response], service.definitions)
        schema = _nullable(response)
        schema["definitions"] = {k: _nullable(v) for k, v in response_defs.items()}
        classes.append(
            _build_class(
                name=camel(action.name) + "Response",
                base="Response",
                description=f"Response of {where} endpoint.",
                fields=response.get("properties") or {},
                required=set(),
                schema=schema,
                definitions=service.definitions,
                where=where + ".response",
                extra=meta,
            )
        )

    template = _env.get_template("module.py.jinja2")
    return template.render(
        service=service,
        title=title,
        description=_clean(service.description),
        header=HEADER,
        session_package=session_package,
        classes=models + classes + batches,
        enums=enums,
        batched=bool(batches),
        compound=any(c["base"] == "CompoundRequest" for c in classes),
        mapping=[(camel(a.name) + "Request", camel(a.name) + "Response") for a in actions],
    )
