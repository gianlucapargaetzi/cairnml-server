"""
Renders the Python module of one service: today's class shape (Request, Response, NonStrictDataModel,
schema_property) for the newest definition of every action. The templates make the final text, no formatter runs
afterwards, so the output does not depend on a formatter version. Nothing in it depends on the date, the machine or
the schema's location.
"""

import json
import keyword
import re
from dataclasses import dataclass
from pathlib import Path
from typing import List

import jinja2

from .schema_model import Action, Service, ref_name, reachable_definitions

LINE_WIDTH = 100
HEADER = (
    "# Generated by apiserver.client_generator from the cairnml-server schema. "
    "Do not edit: change the schema, then regenerate."
)

_env = jinja2.Environment(
    loader=jinja2.FileSystemLoader(str(Path(__file__).parent / "templates")),
    autoescape=False,
    trim_blocks=True,
    lstrip_blocks=True,
    keep_trailing_newline=True,
    undefined=jinja2.StrictUndefined,
)


class Unsupported(Exception):
    """The schema uses something the generator does not render yet."""


def camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_\s]+", name) if part)


# ---------------------------------------------------------------------------------------------------------------------
# Python literal of the schema dicts


def _inline(value) -> str:
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(k)}: {_inline(v)}" for k, v in sorted(value.items())) + "}"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_inline(v) for v in value) + "]"
    if value is None or isinstance(value, bool):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def literal(value, indent: int, prefix: str = "", suffix: str = "") -> str:
    """The value as Python source, on one line when it fits, else one entry per line (keys sorted)."""
    inline = _inline(value)
    if len(" " * indent + prefix + inline + suffix) <= LINE_WIDTH or not isinstance(value, (dict, list, tuple)):
        return inline
    pad = " " * (indent + 4)
    opening, closing = ("{", "}") if isinstance(value, dict) else ("[", "]")
    lines = [opening]
    items = sorted(value.items()) if isinstance(value, dict) else [(None, v) for v in value]
    for key, child in items:
        key_prefix = f"{json.dumps(key)}: " if key is not None else ""
        lines.append(f"{pad}{key_prefix}{literal(child, indent + 4, key_prefix, ',')},")
    lines.append(" " * indent + closing)
    return "\n".join(lines)


# ---------------------------------------------------------------------------------------------------------------------
# Types


@dataclass
class Kind:
    name: str  # str, datetime, int, float, bool, dict, any, ref, list
    cls: str = ""  # for ref: the class name
    item: "Kind" = None  # for list

    @property
    def hint(self) -> str:
        if self.name == "list":
            return f"List[{self.item.hint}]"
        return {
            "str": "str",
            "datetime": "str",
            "int": "int",
            "float": "float",
            "bool": "bool",
            "dict": "dict",
        }.get(self.name, "Any")

    @property
    def doc(self) -> str:
        if self.name == "list":
            return f"Sequence[{self.item.doc}]"
        return {"datetime": "datetime.datetime", "ref": self.cls}.get(self.name, self.name)


_SIMPLE = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict"}
_UNSUPPORTED_KEYS = ("oneOf", "anyOf", "allOf", "not", "patternProperties")


def kind_of(schema: dict, definitions: dict, where: str, depth: int = 0) -> Kind:
    for key in _UNSUPPORTED_KEYS:
        if key in schema:
            raise Unsupported(f"{where}: `{key}` is not supported yet")
    if "$ref" in schema:
        name = ref_name(schema["$ref"])
        target = definitions[name]
        if target.get("type") == "object" and "properties" in target:
            return Kind("ref", cls=camel(name))
        # a definition that is a plain type (for example a string enumeration): the field has that type
        return kind_of(target, definitions, f"{where} -> {name}", depth)
    type_ = schema.get("type")
    if type_ is None:
        return Kind("any")
    if not isinstance(type_, str):
        raise Unsupported(f"{where}: a list of types is not supported yet")
    if type_ == "array":
        if depth:
            raise Unsupported(f"{where}: arrays of arrays are not supported yet")
        item = kind_of(schema.get("items") or {}, definitions, f"{where}[]", depth + 1)
        return Kind("list", item=item)
    if type_ not in _SIMPLE:
        raise Unsupported(f"{where}: type {type_!r} is not supported")
    if type_ == "string" and schema.get("format") == "date-time":
        return Kind("datetime")
    return Kind(_SIMPLE[type_])


def _setter_lines(name: str, kind: Kind) -> List[str]:
    q = json.dumps(name)
    if kind.name == "list":
        lines = [f"self.assert_isinstance(value, {q}, (list, tuple))"]
        item = kind.item
        if item.name == "int":
            lines += [
                "value = [int(v) if isinstance(v, float) and v.is_integer() else v for v in value]",
                f"self.assert_isinstance(value, {q}, six.integer_types, is_array=True)",
            ]
        elif item.name == "ref":
            lines += [
                "if any((isinstance(v, dict) for v in value)):",
                f"    value = [{item.cls}.from_dict(v) if isinstance(v, dict) else v for v in value]",
                "else:",
                f"    self.assert_isinstance(value, {q}, {item.cls}, is_array=True)",
            ]
        elif item.name == "datetime":
            lines += [
                f"self.assert_isinstance(value, {q}, six.string_types + (datetime,), is_array=True)",
                "value = [v if isinstance(v, datetime) else parse_datetime(v) for v in value]",
            ]
        elif item.name != "any":
            lines.append(f"self.assert_isinstance(value, {q}, {_types(item)}, is_array=True)")
        return lines
    if kind.name == "int":
        return [
            "if isinstance(value, float) and value.is_integer():",
            "    value = int(value)",
            f"self.assert_isinstance(value, {q}, six.integer_types)",
        ]
    if kind.name == "datetime":
        return [
            f"self.assert_isinstance(value, {q}, six.string_types + (datetime,))",
            "if not isinstance(value, datetime):",
            "    value = parse_datetime(value)",
        ]
    if kind.name == "ref":
        return [
            "if isinstance(value, dict):",
            f"    value = {kind.cls}.from_dict(value)",
            "else:",
            f"    self.assert_isinstance(value, {q}, {kind.cls})",
        ]
    if kind.name == "any":
        return []
    return [f"self.assert_isinstance(value, {q}, {_types(kind)})"]


def _types(kind: Kind) -> str:
    return {
        "str": "six.string_types",
        "float": "six.integer_types + (float,)",
        "bool": "(bool,)",
        "dict": "(dict,)",
    }[kind.name]


# ---------------------------------------------------------------------------------------------------------------------
# Views for the template


@dataclass
class Prop:
    name: str
    hint: str
    required: bool
    setter: List[str]

    @property
    def annotation(self) -> str:
        return self.hint if self.required or self.hint == "Any" else f"Optional[{self.hint}]"


def _clean(text) -> str:
    text = " ".join(str(text).split())
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _nullable(schema: dict) -> dict:
    """Responses and data models accept null for every property the server may leave out."""
    result = dict(schema)
    if "properties" in result:
        properties = {}
        for key, prop in result["properties"].items():
            prop = dict(prop)
            if "$ref" in prop:
                ref = prop.pop("$ref")
                prop["oneOf"] = [{"$ref": ref}, {"type": "null"}]
            elif isinstance(prop.get("type"), str):
                prop["type"] = [prop["type"], "null"]
            properties[key] = prop
        result["properties"] = properties
    return result


def _build_class(*, name, base, description, fields, required, schema, definitions, where, extra=None):
    kinds = {}
    for field_name, field_schema in fields.items():
        if keyword.iskeyword(field_name):
            raise Unsupported(f"{where}: the field name {field_name!r} is a Python keyword")
        kinds[field_name] = kind_of(field_schema, definitions, f"{where}.{field_name}")
    order = [n for n in fields if n in required] + [n for n in fields if n not in required]
    props = [Prop(n, kinds[n].hint, n in required, _setter_lines(n, kinds[n])) for n in order]
    params = []
    for n in order:
        if n in required:
            params.append(f"{n}: {kinds[n].hint}")
        else:
            default = fields[n].get("default")
            if isinstance(default, (list, dict)):
                raise Unsupported(f"{where}.{n}: a list or object default is not supported (mutable default)")
            hint = kinds[n].hint
            params.append(f"{n}: {hint if hint == 'Any' else f'Optional[{hint}]'} = {_inline(default)}")
    params.append("**kwargs: Any")
    one_line = f"    def __init__(self, {', '.join(params)}) -> None:"
    if len(one_line) <= LINE_WIDTH:
        signature = one_line
    else:
        signature = "    def __init__(\n        self,\n" + "".join(f"        {p},\n" for p in params[:-1])
        signature += "        **kwargs: Any\n    ) -> None:"
    doc = [_clean(description)] if description else []
    params_doc = []
    for n in order:
        text = _clean(fields[n].get("description", ""))
        params_doc.append(f":param {n}: {text}".rstrip())
        params_doc.append(f":type {n}: {kinds[n].doc}")
    return {
        "name": name,
        "base": base,
        "doc": doc,
        "params_doc": params_doc,
        "schema": literal(schema, 4, "_schema = "),
        "signature": signature,
        "props": props,
        "order": order,
        "extra": extra,
    }


def _request_fields(action: Action):
    if not action.request:
        raise Unsupported(f"{action.full_name}: no `request` (batch requests are not supported yet)")
    request = action.request
    if "properties" not in request and request.get("type", "object") != "object":
        raise Unsupported(f"{action.full_name}: the request is not an object")
    return request.get("properties") or {}, set(request.get("required") or [])


def render_service(service: Service, session_package: str) -> str:
    actions = [service.actions[name] for name in sorted(service.actions)]
    fragments = [a.request for a in actions] + [a.response for a in actions]
    for action in actions:
        _request_fields(action)  # fail early with the action's name
    used = reachable_definitions(fragments, service.definitions)

    models = []
    for def_name, definition in used.items():
        if definition.get("type") != "object" or "properties" not in definition:
            continue  # a plain type: fields that refer to it get its type
        own = reachable_definitions([definition], service.definitions)
        schema = _nullable(definition)
        if own:
            schema["definitions"] = {k: _nullable(v) for k, v in own.items()}
        models.append(
            _build_class(
                name=camel(def_name),
                base="NonStrictDataModel",
                description=definition.get("description", ""),
                fields=definition["properties"],
                required=set(),
                schema=schema,
                definitions=service.definitions,
                where=f"{service.name}.{def_name}",
            )
        )
    models.sort(key=lambda m: m["name"])

    classes = []
    for action in actions:
        where = f"{service.name}.{action.name}"
        meta = {"service": service.name, "action": action.name, "version": action.version}
        fields, required = _request_fields(action)
        request_defs = reachable_definitions([action.request], service.definitions)
        schema = dict(action.request)
        schema["definitions"] = request_defs
        classes.append(
            _build_class(
                name=camel(action.name) + "Request",
                base="Request",
                description=action.description,
                fields=fields,
                required=required,
                schema=schema,
                definitions=service.definitions,
                where=where + ".request",
                extra=meta,
            )
        )
        response = action.response
        response_defs = reachable_definitions([response], service.definitions)
        schema = _nullable(response)
        schema["definitions"] = {k: _nullable(v) for k, v in response_defs.items()}
        classes.append(
            _build_class(
                name=camel(action.name) + "Response",
                base="Response",
                description=f"Response of {where} endpoint.",
                fields=response.get("properties") or {},
                required=set(),
                schema=schema,
                definitions=service.definitions,
                where=where + ".response",
                extra=meta,
            )
        )

    template = _env.get_template("module.py.jinja2")
    return template.render(
        service=service,
        description=_clean(service.description),
        header=HEADER,
        session_package=session_package,
        classes=models + classes,
        mapping=[(camel(a.name) + "Request", camel(a.name) + "Response") for a in actions],
    )
