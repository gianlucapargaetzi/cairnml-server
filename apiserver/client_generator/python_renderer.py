# Types


@dataclass
class Kind:
    name: str  # str, datetime, int, float, bool, dict, any, ref, enum, list
    cls: str = ""  # for ref and enum: the class name
    item: "Kind" = None  # for list

    @property
    def hint(self) -> str:
        if self.name == "list":
            return f"List[{self.item.hint}]"
        return {
            "str": "str",
            "datetime": "str",
            "int": "int",
            "float": "float",
            "bool": "bool",
            "dict": "dict",
            "enum": "str",  # a member is a Enum, a value that is not a member of it stays a string
        }.get(self.name, "Any")

    @property
    def doc(self) -> str:
        if self.name == "list":
            return f"Sequence[{self.item.doc}]"
        return {"datetime": "datetime.datetime", "ref": self.cls, "enum": self.cls}.get(self.name, self.name)


_SIMPLE = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict"}
_UNSUPPORTED_KEYS = ("oneOf", "anyOf", "allOf", "not", "patternProperties")


def kind_of(schema: dict, definitions: dict, where: str, depth: int = 0) -> Kind:
    if "anyOf" in schema or "oneOf" in schema:
        members = [m for m in (schema.get("anyOf") or schema.get("oneOf") or []) if m.get("type") != "null"]
        if len(members) == 1 and "$ref" in members[0]:
            # a nullable reference (a definition or null): the reference
            return kind_of(members[0], definitions, where, depth)
        if not members:
            raise Unsupported(f"{where}: a union without a shape")
        # several shapes (for example an id string or an object the server expands): the value is not one type
        return Kind("any")
    for key in _UNSUPPORTED_KEYS:
        if key in schema:
            raise Unsupported(f"{where}: `{key}` is not supported yet")
    if "$ref" in schema:
        name = ref_name(schema["$ref"])
        target = definitions[name]
        if target.get("type") == "object" and "properties" in target:
            return Kind("ref", cls=camel(name))
        if "enum" in target:
            return Kind("enum", cls=camel(name))
        # a definition that is a plain type (for example a string enumeration): the field has that type
        return kind_of(target, definitions, f"{where} -> {name}", depth)
    type_ = schema.get("type")
    if type_ is None:
        return Kind("any")
    if not isinstance(type_, str):
        # only the nullable form, one type and null, is a type: the field has that type
        # HOCON reads null as None
        non_null = [t for t in type_ if t not in ("null", None)]
        if len(non_null) != 1 or len(non_null) + 1 != len(type_):
            raise Unsupported(f"{where}: a list of types {type_!r} is not supported yet")
        type_ = non_null[0]
        schema = {**schema, "type": type_}
    if type_ == "array":
        item = kind_of(schema.get("items") or {}, definitions, f"{where}[]", depth + 1)
        return Kind("list", item=item)
    if type_ not in _SIMPLE:
        raise Unsupported(f"{where}: type {type_!r} is not supported")
    if type_ == "string" and schema.get("format") == "date-time":
        return Kind("datetime")
    return Kind(_SIMPLE[type_])


def _setter_lines(name: str, kind: Kind) -> List[str]:
    q = json.dumps(name)
    if kind.name == "list":
        lines = [f"self.assert_isinstance(value, {q}, (list, tuple))"]
        item = kind.item
        if item.name == "int":
            lines += [
                "value = [int(v) if isinstance(v, float) and v.is_integer() else v for v in value]",
                f"self.assert_isinstance(value, {q}, six.integer_types, is_array=True)",
            ]
        elif item.name == "ref":
            lines += [
                "if any((isinstance(v, dict) for v in value)):",
                f"    value = [{item.cls}.from_dict(v) if isinstance(v, dict) else v for v in value]",
                "else:",
                f"    self.assert_isinstance(value, {q}, {item.cls}, is_array=True)",
            ]
        elif item.name == "datetime":
            lines += [
                f"self.assert_isinstance(value, {q}, six.string_types + (datetime,), is_array=True)",
                "value = [v if isinstance(v, datetime) else parse_datetime(v) for v in value]",
            ]
        elif item.name == "enum":
            # a value that is not a member of the enumeration stays a string (a newer server may send one)
            lines += [
                "converted = []",
                "for v in value:",
                "    if isinstance(v, six.string_types):",
                "        try:",
                f"            v = {item.cls}(v)",
                "        except ValueError:",
                "            pass",
                "    converted.append(v)",
                "value = converted",
                f"self.assert_isinstance(value, {q}, six.string_types + (enum.Enum,), is_array=True)",
            ]
        elif item.name != "any":
            lines.append(f"self.assert_isinstance(value, {q}, {_types(item)}, is_array=True)")
        return lines
    if kind.name == "int":
        return [
            "if isinstance(value, float) and value.is_integer():",
            "    value = int(value)",
            f"self.assert_isinstance(value, {q}, six.integer_types)",
        ]
    if kind.name == "datetime":
        return [
            f"self.assert_isinstance(value, {q}, six.string_types + (datetime,))",
            "if not isinstance(value, datetime):",
            "    value = parse_datetime(value)",
        ]
    if kind.name == "enum":
        # the string becomes the member; a member is kept; a string that is not a value of the enumeration is kept
        return [
            "if isinstance(value, six.string_types):",
            "    try:",
            f"        value = {kind.cls}(value)",
            "    except ValueError:",
            "        pass",
            "else:",
            f"    self.assert_isinstance(value, {q}, enum.Enum)",
        ]
    if kind.name == "ref":
        return [
            "if isinstance(value, dict):",
            f"    value = {kind.cls}.from_dict(value)",
            "else:",
            f"    self.assert_isinstance(value, {q}, {kind.cls})",
        ]
    if kind.name == "any":
        return []
    return [f"self.assert_isinstance(value, {q}, {_types(kind)})"]


def _types(kind: Kind) -> str:
    return {
        "str": "six.string_types",
        "float": "six.integer_types + (float,)",
        "bool": "(bool,)",
        "dict": "(dict,)",
        "list": "(list, tuple)",
    }[kind.name]


