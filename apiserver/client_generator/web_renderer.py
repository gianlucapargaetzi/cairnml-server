"""
Renders the web app's API layer (TypeScript) from the schema, in the form the web app already imports:
- `api-services/<service>.service.ts`: one method per action, `<service><Action>(request, options)`, which posts to
  `${basePath}/v<version>/<service>.<action>` (the version of the action's definition) through `SmApiRequestsService`.
  The few actions of UNVERSIONED_ACTIONS are posted to `${basePath}/<service>.<action>`, without a version;
- `model/<service>/<name>.ts`: an interface per request and response, one per nested object (named after its parent),
  one per definition of the schema, a `<name>Enum` for an enumeration definition, and a namespace for an inline
  enumeration; `models.ts` re-exports them.

Names follow the existing files exactly, so the app's imports keep working. A construct the renderer does not know
raises Unsupported and nothing is written.
"""

import re
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

from .python_renderer import Unsupported
from .schema_model import Action, Service

HEADER = """/**
 * {service}
 * No description provided (generated by Openapi Generator https://github.com/openapitools/openapi-generator)
 *
 * OpenAPI spec version: {version}
 *
 *
 * NOTE: This class is auto generated by the swagger code generator program.
 * https://github.com/swagger-api/swagger-codegen.git
 * Do not edit the class manually.
 */
"""


# Actions the web app calls WITHOUT a version, with the reason. The server serves a path without a version with the
# newest definition (service_repo: no version means the newest API version), so such a call never goes stale. Only the
# addresses that a browser or the identity provider keeps independent of the API version are in it:
# - login.logout: the ID-token cookie that lets the identity provider end the session without asking to confirm is
#   scoped by path to `/cairnml/api/login.logout` (apiserver.auth.custom_cookies.idp_session in apiserver.conf). A
#   cookie is sent only on a request whose path starts with its Path, so a call at `/v<version>/login.logout` would
#   not carry it;
# - login.idp_start, login.idp_callback: the identity provider keeps these addresses (the realm lists the callback),
#   and the server hands them out without a version (idp/public_origin.py), so a version would stop matching after an
#   upgrade.
UNVERSIONED_ACTIONS = {
    "login.logout": "the path of its ID-token cookie has no version",
    "login.idp_start": "the identity provider keeps this address",
    "login.idp_callback": "the identity provider keeps this address",
}


def action_path(service: str, action: Action) -> str:
    """The path of an action below the API's base path: at the version of its definition, or without a version for the
    actions of UNVERSIONED_ACTIONS."""
    full = f"{service}.{action.name}"
    return f"/{full}" if full in UNVERSIONED_ACTIONS else f"/v{action.version}/{full}"


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_\W]+", name) if part)


def lower_first(name: str) -> str:
    return name[:1].lower() + name[1:]


def _doc(text: Optional[str], indent: str) -> List[str]:
    if not text:
        return []
    clean = re.sub(r"\s+", " ", str(text)).strip().replace("'", "\\'")
    return [f"{indent}/**", f"{indent} * {clean}", f"{indent} */"]


def _ref_name(ref: str) -> str:
    return ref.split("/")[-1]


@dataclass
class TsFile:
    name: str  # file stem, lower first (for example tasksGetAllExRequest)
    text: str


class Models:
    """Collects the files of one service's models. A type name is the file name with its first letter upper case."""

    def __init__(self, service: Service):
        self.service = service
        self.files: Dict[str, str] = {}  # stem -> text
        self.done_defs: Dict[str, str] = {}  # definition -> type name
        self.root = ""  # the top-level type being rendered; nested objects are named root + Field
        self.version = ""  # the block version the files are written for: the action being rendered, else the service's

    def _emit(self, type_name: str, body: str, imports: List[str], doc: List[str], namespace: str = "") -> None:
        stem = lower_first(type_name)
        head = HEADER.format(service=self.service.name, version=self.version)
        imports_text = "".join(
            f"import {{ {n} }} from '././{lower_first(n)}';\n" for n in sorted(set(imports)) if n != type_name
        )
        block = "\n".join(doc) + ("\n" if doc else "")
        self.files[stem] = f"{head}\n{imports_text}\n\n{block}export interface {type_name} {{\n{body}}}\n{namespace}"

    def _type(self, schema: dict, parent: str, field: str, imports: List[str], extra: List[str]) -> str:
        """The TypeScript type of a schema fragment. Objects with properties get their own file named parent+Field."""
        if "$ref" in schema:
            target = _ref_name(schema["$ref"])
            definition = self.service.definitions.get(target)
            if definition is None:
                raise Unsupported(f"{parent}.{field}: the definition {target!r} does not exist")
            if definition.get("type") == "object" and "properties" in definition:
                name = pascal(target)
                imports.append(name)
                self._def(target)
                return name
            if "enum" in definition:
                name = pascal(target)
                imports.append(name)
                self._def(target)
                return name
            return self._type(definition, parent, field, imports, extra)
        if "anyOf" in schema or "oneOf" in schema:
            # a field that is one of several shapes: each member is rendered, a null member is the field being optional
            members = schema.get("anyOf") or schema.get("oneOf") or []
            rendered = []
            for member in members:
                if member.get("type") == "null":
                    continue
                text = self._type(member, parent, field, imports, extra)
                if text not in rendered:
                    rendered.append(text)
            if not rendered:
                raise Unsupported(f"{parent}.{field}: a union without a shape")
            return " | ".join(rendered)
        type_ = schema.get("type")
        if isinstance(type_, list):
            non_null = [t for t in type_ if t not in ("null", None)]
            if len(non_null) != 1:
                raise Unsupported(f"{parent}.{field}: a list of types {type_!r} is not supported")
            type_ = non_null[0]
            schema = {**schema, "type": type_}
        if "enum" in schema and type_ == "string":
            # an inline enumeration: a namespace member of the parent type, named <Field>Enum
            enum_name = pascal(field) + "Enum"
            values = [v for v in schema["enum"] if v is not None]
            extra.append(_enum_namespace(parent, enum_name, values))
            return f"{parent}.{enum_name}"
        if type_ == "array":
            item = self._type(schema.get("items") or {}, parent, field, imports, extra)
            return f"{item}[]"
        if type_ == "object" and "properties" in schema:
            name = self.root + pascal(field)
            self._object(name, schema, imports=[])
            imports.append(name)
            return name
        if type_ == "object":
            extra_props = schema.get("additionalProperties")
            if isinstance(extra_props, dict) and extra_props:
                return f"Record<string, {self._type(extra_props, parent, field, imports, extra)}>"
            # an object with no declared fields: any values under any key (the contract does not describe them)
            return "Record<string, any>"
        if type_ == "string":
            return "string"
        if type_ in ("integer", "number"):
            return "number"
        if type_ == "boolean":
            return "boolean"
        if type_ is None:
            return "any"
        raise Unsupported(f"{parent}.{field}: type {type_!r} is not supported")

    def _object(self, type_name: str, schema: dict, imports: List[str], doc: str = "") -> None:
        outer_root = self.root
        self.root = self.root or type_name
        props = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        lines: List[str] = []
        extra: List[str] = []
        local_imports: List[str] = []
        for field, prop in props.items():
            ptype = self._type(prop, type_name, field, local_imports, extra)
            for line in _doc(prop.get("description"), "    "):
                lines.append(line)
            key = field if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", field) else f"'{field}'"
            lines.append(f"    {key}{'' if field in required else '?'}: {ptype};")
        body = "".join(line + "\n" for line in lines)
        namespace = "".join(extra)
        self.root = outer_root
        self._emit(type_name, body, local_imports, _doc(doc, ""), namespace)

    def _def(self, name: str) -> None:
        if name in self.done_defs:
            return
        definition = self.service.definitions[name]
        type_name = pascal(name)
        self.done_defs[name] = type_name
        if "enum" in definition:
            values = [v for v in definition["enum"] if v is not None]
            stem = lower_first(type_name)
            head = HEADER.format(service=self.service.name, version=self.version)
            self.files[stem] = head + "\n" + _enum_definition(type_name, values, definition.get("description"))
            return
        # the objects nested in a definition are named after the definition, not after the action that uses it
        outer_root = self.root
        self.root = type_name
        try:
            self._object(type_name, definition, imports=[], doc=definition.get("description", ""))
        finally:
            self.root = outer_root

    def action(self, action: Action) -> Tuple[str, str]:
        """Writes the request and the response of one action; returns their type names."""
        self.version = action.version
        names = []
        for kind, schema in (("Request", action.request), ("Response", action.response)):
            name = f"{pascal(self.service.name)}{pascal(action.name)}{kind}"
            names.append(name)
            if not schema:
                self._emit(name, "", [], _doc(action.description, ""))
                continue
            if "$ref" in schema:
                # the request or response is a named definition: the action's type is that definition
                imports: List[str] = []
                target = self._type(schema, name, kind, imports, [])
                stem = lower_first(name)
                head = HEADER.format(service=self.service.name, version=self.version)
                self.files[stem] = (
                    f"{head}\nimport {{ {target} }} from '././{lower_first(target)}';\n\nexport type {name} = {target};\n"
                )
                continue
            self.root = ""
            self._object(name, schema, imports=[], doc=action.description if kind == "Request" else "")
        return names[0], names[1]


def _enum_definition(type_name: str, values: List[str], description: Optional[str]) -> str:
    union = " | ".join(f"'{v}'" for v in values)
    members = "".join(f"    {pascal(str(v)) or '_'}: '{v}' as {type_name},\n" for v in values)
    doc = "\n".join(_doc(description, ""))
    doc = doc + "\n" if doc else ""
    return f"{doc}export type {type_name} = {union};\n\nexport const {type_name} = {{\n{members}}}\n"


def _enum_namespace(parent: str, enum_name: str, values: List[str]) -> str:
    union = " | ".join(f"'{v}'" for v in values)
    members = "".join(f"        {pascal(str(v)) or '_'}: '{v}' as {enum_name},\n" for v in values)
    return (
        f"export namespace {parent} {{\n    export type {enum_name} = {union};\n"
        f"    export const {enum_name} = {{\n{members}    }}\n}}\n"
    )


def _service_version(service: Service) -> str:
    """The highest block version of the service's actions: the version its files are written for."""
    versions = [action.version for action in service.actions.values()]
    return max(versions, key=lambda v: tuple(int(part) for part in v.split("."))) if versions else ""


ENDPOINTS = """{head}
import {HTTP} from '../../app.constants';

/**
 * The version of each action of the server's schema: the version of its definition. null: the action is called without
 * a version (the server then serves its newest definition). Generated from the schema.
 */
const ACTION_VERSIONS = new Map<string, string | null>([
@@ENTRIES@@]);

/**
 * The URL of an action at the version of its definition. An action the schema does not have is an error: a call is
 * never sent at a version written by hand or at the latest one by default.
 */
export const endpointUrl = (action: string): string => {
    if (!ACTION_VERSIONS.has(action)) {
        throw new Error(`${action} is not an action of the server's schema`);
    }
    const version = ACTION_VERSIONS.get(action);
    return version === null ? `${HTTP.API_BASE_URL}/${action}` : `${HTTP.API_BASE_URL}/v${version}/${action}`;
};
"""


def render_endpoints(schema: Dict[str, Service]) -> str:
    """api-services/endpoints.ts: the version of every action and endpointUrl, which addresses an action at that version.
    The hand-written calls use it, so no call carries a version written by hand."""
    actions = [
        (f"{service}.{name}", schema[service].actions[name])
        for service in sorted(schema)
        for name in sorted(schema[service].actions)
    ]
    stale = sorted(set(UNVERSIONED_ACTIONS) - {name for name, _ in actions})
    if stale:
        raise Unsupported(f"UNVERSIONED_ACTIONS names {stale}, which the schema does not have")
    entries = "".join(
        f"    ['{name}', {'null' if name in UNVERSIONED_ACTIONS else repr(action.version)}],\n"
        for name, action in actions
    )
    newest = max(
        (action.version for _, action in actions), key=lambda v: tuple(int(part) for part in v.split(".")), default=""
    )
    head = HEADER.format(service="endpoints", version=newest)
    return ENDPOINTS.replace("{head}", head).replace("@@ENTRIES@@", entries)


def render_models(service: Service) -> Dict[str, str]:
    models = Models(service)
    for name in sorted(service.actions):
        models.action(service.actions[name])
    # every definition of the schema, reached or not: the web app imports some of them by name from the barrel
    models.version = _service_version(service)
    for name in list(service.definitions):
        models._def(name)
    return models.files


def render_api(service: Service) -> str:
    """The service class: one method per action, posting to the server's action name."""
    cls = f"Api{pascal(service.name)}Service"
    imports = set()
    methods = []
    for name in sorted(service.actions):
        action = service.actions[name]
        if action.batch_request:
            continue  # batched requests are sent by the batching service, not by a method of their own
        method = f"{service.name}{pascal(action.name)}"
        req = f"{pascal(service.name)}{pascal(action.name)}Request"
        res = f"{pascal(service.name)}{pascal(action.name)}Response"
        imports.update([req, res])
        methods.append(
            "\n".join(_doc(action.description, "    "))
            + ("\n" if action.description else "")
            + f"    public {method}(request: {req}, options?: ApiOptions): Observable<any> {{\n"
            + f"        return this.apiRequest.post<{res}>(`${{this.basePath}}{action_path(service.name, action)}`,\n"
            + "            request,\n"
            + "            {\n"
            + "                headers: this.defaultHeaders,\n"
            + "                withCredentials: this.configuration.withCredentials\n"
            + "            },\n"
            + "            options\n"
            + "        );\n"
            + "    }\n"
        )
    import_lines = "".join(
        f"import {{ {n} }} from '../model/{service.name}/{lower_first(n)}';\n" for n in sorted(imports)
    )
    return (
        HEADER.format(service=service.name, version=_service_version(service))
        + "\n/* eslint-disable @typescript-eslint/no-unused-vars, @typescript-eslint/member-ordering */\n\n"
        + "import {HTTP} from '../../app.constants';\n"
        + "import {SmApiRequestsService} from './api-requests.service';\n"
        + "import {Inject, Injectable, Optional} from '@angular/core';\n"
        + "import {HttpHeaders} from '@angular/common/http';\n"
        + "import {Observable} from 'rxjs';\n"
        + "import {ApiOptions} from './api';\n"
        + import_lines
        + "import {BASE_PATH} from '../variables';\n"
        + "import {Configuration} from '../configuration';\n\n\n"
        + "@Injectable({providedIn: 'root'})\n"
        + f"export class {cls} {{\n\n"
        + "    protected basePath = HTTP.API_BASE_URL;\n"
        + "    public defaultHeaders = new HttpHeaders({'Accept': 'application/json'});\n"
        + "    public configuration = new Configuration();\n\n"
        + "    constructor(protected apiRequest: SmApiRequestsService, @Optional() @Inject(BASE_PATH) basePath: string, @Optional() configuration: Configuration) {\n"
        + "        if (basePath) {\n            this.basePath = basePath;\n        }\n"
        + "        if (configuration) {\n            this.configuration = configuration;\n"
        + "            this.basePath = basePath || configuration.basePath || this.basePath;\n        }\n    }\n\n"
        + "\n".join(methods)
        + "}\n"
    )
