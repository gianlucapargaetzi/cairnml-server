"""
Checks the hand-written callers of the API in Python source against the schema:
- a request class of a generated service (`queues.CreateRequest(...)`) must name an action the schema has;
- a keyword of its constructor must be a field of that action's newest request;
- a call with literal `service=`, `action=` keywords must name an action the schema has, and a literal `version=` must
  be a version the schema declares for it;
- a string that is an API version (`2.40`, `/v2.8/` in a URL) is not written in hand-written code at all: the version
  comes from the generated classes. The generated modules themselves are not checked for this, and the argument of
  `check_min_server_version` is a server version, not an API version, so it is not judged;
- a call of `send_request`, `get`, `post` or `send` (on any object) that names its service and action as strings (with
  `service=` and `action=`, or as the first two positional arguments) and names an action of the schema is reported:
  the generated request class of that action is to be built and sent instead, so a renamed field fails at generation
  or in this check, not at run time. Generated modules are not judged for this. A forwarding call that takes the
  service and action from variables is not a literal and is not reported;
- with `sessions=True`, a method called on a session object must be a method of the Session class (the class named
  `Session` in the scanned tree, with the classes it inherits from). A session object is a name `session`, `_session`
  or `task_session`, an attribute of that name (`self._session`), a name assigned from `Session(...)` of the SDK or the
  agent or annotated `Session`, but not a name bound to `requests`. A session may be a plain `requests.Session`, so the
  methods of `requests.Session` and of `object` are accepted as well. A base class is resolved through the import that
  names it, so `class Session(SdkSession)` with `from cairnml.backend_api.session.session import Session as SdkSession`
  inherits from the SDK's Session and not from the class of its own name. A base that the scanned folder and the
  `bases` folders do not define is reported, since its methods cannot be checked. The `bases` folders (the agent's
  check passes the SDK's package) are read for their classes only; they are not checked;
- in a test file (`test_*.py`, `*_test.py`, `conftest.py`, or a file under a `tests` folder that is not in `fixtures`) a
  version string is an API version only when it picks the version of a request: the value of a `version=` keyword or
  a `/vX.Y/` in a URL, and not inside an assertion or a comparison. Any other string in a test is test data (a version
  of a fake server, a compared value, a requirement or interpreter version). Other files are judged as above.

The allow file has one line per exception, `exempt <service.action> <reason>` (the reason is mandatory); blank lines and
lines starting with `#` are ignored. An exception that matches no call is reported, so the file only holds current drift.

Exit codes of the command: 0 when nothing is reported, 1 when something is reported, 2 for a usage error (a missing
folder, an unreadable schema, a bad allow file).
"""

import ast
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Set, Tuple

import requests

from .python_renderer import camel
from .schema_model import Service

GENERATED_PREFIX = "# Generated by apiserver.client_generator"
VERSION_LITERAL = re.compile(r"^/?v?\d+\.\d+/?$")
VERSION_IN_URL = re.compile(r"/v\d+\.\d+/")
SESSION_NAMES = frozenset({"session", "_session", "task_session"})
# the calls on a session object that take a service and an action as their first two arguments
SESSION_SENDERS = frozenset({"send_request", "get", "post", "send"})
TRIVIAL_BASES = frozenset({"object", "ABC", "Exception"})
# a session object may be the plain HTTP session the SDK wraps (requests.Session): its methods are accepted too
HTTP_SESSION_METHODS = frozenset(dir(requests.Session))
SESSION_ROOTS = frozenset(
    {"Session", "cairnml", "cairnml_agent"}
)  # `Session(...)` of the SDK or the agent, not boto3's


@dataclass
class Allow:
    exempt: Dict[str, str] = field(default_factory=dict)
    source: str = "allow file"  # where the exemptions come from, for the report of a stale one


@dataclass
class Finding:
    path: Path
    line: int
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.message}"


def read_allow(path: Path) -> Allow:
    allow = Allow(source=str(path))
    for number, raw in enumerate(Path(path).read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 2)
        if parts[0] != "exempt":
            raise ValueError(f"{path}:{number}: unknown line type {parts[0]!r}")
        if len(parts) < 3 or not parts[2].strip():
            raise ValueError(f"{path}:{number}: `exempt {parts[1] if len(parts) > 1 else '<action>'}` needs a reason")
        allow.exempt[parts[1]] = parts[2].strip()
    return allow


def _string(node):
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _root_name(node) -> Optional[str]:
    """The name at the start of an attribute or call chain: `requests` in `requests.Session().mount`."""
    while isinstance(node, (ast.Attribute, ast.Call)):
        node = node.func if isinstance(node, ast.Call) else node.value
    return node.id if isinstance(node, ast.Name) else None


def _call_name(node) -> Optional[str]:
    """`Session` in `Session(...)` and in `module.Session(...)`."""
    if isinstance(node, ast.Name):
        return node.id
    return node.attr if isinstance(node, ast.Attribute) else None


def _session_names_in(tree) -> Set[str]:
    """`Session`, and the local names it is imported under (`from x import Session as _Session`)."""
    names = {"Session"}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            names |= {alias.asname for alias in node.names if alias.name == "Session" and alias.asname}
    return names


def _annotation_is_session(node, names: Set[str]) -> bool:
    if isinstance(node, ast.Name):
        return node.id in names
    return isinstance(node, ast.Attribute) and node.attr == "Session"


SESSION, FOREIGN = "session", "foreign"  # what a name bound in a scope is
FOREIGN_ROOTS = frozenset({"requests", "httpx", "boto3"})  # libraries whose sessions are not the SDK's


def _value_kind(value, class_names: Set[str]) -> Optional[str]:
    root = _root_name(value)
    if isinstance(value, ast.Call) and _call_name(value.func) in class_names and root in SESSION_ROOTS | class_names:
        return SESSION
    return FOREIGN if root in FOREIGN_ROOTS else None


def _bindings(nodes, class_names: Set[str]) -> Dict[str, str]:
    """What the names bound in these statements are: a Session, or something else from a library (anything else is not
    recorded, so the name heuristic applies to it)."""
    found: Dict[str, str] = {}
    for top in nodes:
        for node in ast.walk(top):
            if isinstance(node, ast.arg):
                if node.annotation is not None:
                    found[node.arg] = SESSION if _annotation_is_session(node.annotation, class_names) else FOREIGN
                continue
            if isinstance(node, ast.Assign):
                targets, value = node.targets, node.value
            elif isinstance(node, ast.AnnAssign) and node.value is not None:
                targets, value = [node.target], node.value
            else:
                continue
            kind = _value_kind(value, class_names)
            for target in targets:
                if isinstance(target, ast.Name) and kind:
                    found[target.id] = kind
    return found


def _module_name(path: Path, folder: Path) -> Tuple[str, bool]:
    """The dotted module name of a file under the folder it is scanned from (`cairnml_agent.session`), and whether the
    file is a package (`__init__.py`)."""
    rel = path.name if Path(folder).is_file() else path.relative_to(folder).as_posix()
    parts = rel[: -len(".py")].split("/")
    is_package = parts[-1] == "__init__"
    if is_package:
        parts = parts[:-1]
    return ".".join(parts), is_package


def _is_test_file(path: Path, folder: Path) -> bool:
    rel = path.name if Path(folder).is_file() else path.relative_to(folder).as_posix()
    parts = rel.split("/")
    name, folders = parts[-1], parts[:-1]
    if name.startswith("test_") or name.endswith("_test.py") or name == "conftest.py":
        return True
    return "tests" in folders and "fixtures" not in folders


def _imports_in(tree, module: str, is_package: bool) -> Dict[str, Tuple[str, str]]:
    """What the names imported in a file are: `from m import A as B` maps B to (m, A), `import m as x` maps x to (m, '')."""
    package = module if is_package else module.rpartition(".")[0]
    names: Dict[str, Tuple[str, str]] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            anchor: List[str] = []
            if node.level:
                anchor = package.split(".") if package else []
                if node.level > 1:
                    anchor = anchor[: max(len(anchor) - (node.level - 1), 0)]
            base = ".".join(anchor + ([node.module] if node.module else []))
            for alias in node.names:
                names[alias.asname or alias.name] = (base, alias.name)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    names[alias.asname] = (alias.name, "")
    return names


ClassRef = Optional[Tuple[str, str]]  # (module, class name); None when the base is not a name the file can resolve


def _base_ref(node, module: str, imports: Dict[str, Tuple[str, str]]) -> Tuple[ClassRef, str]:
    """The class a base expression names, and the expression as written (for a message)."""
    if isinstance(node, ast.Name):
        if node.id in imports:
            origin, attr = imports[node.id]
            return ((origin, attr) if attr else None), node.id
        return (module, node.id), node.id  # defined in the same module, or not resolvable
    if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name) and node.value.id in imports:
        origin, attr = imports[node.value.id]
        if not attr:
            return (origin, node.attr), ast.unparse(node)
    return None, ast.unparse(node)


@dataclass
class _ClassInfo:
    name: str
    root: bool  # defined under the scanned root (checked) rather than in a bases folder (only read)
    bases: List[Tuple[ClassRef, str]]  # the class each base names, and the base as written
    members: Set[str]  # methods, class attributes and the attributes assigned on self
    dynamic: bool  # defines __getattr__: any attribute may exist


def _class_index(entries, root: bool, prefix: str, plain: bool) -> Dict[Tuple[str, str], List[_ClassInfo]]:
    """The classes of the files, by (module, name). A module is named as the file is scanned (`cairnml_agent.session`)
    and, with `prefix` (the folder's own name, `cairnml` for the SDK's package), as an import names it. `plain` is
    false for a bases folder: its classes are only reachable by the prefixed name, so they cannot shadow the root's."""
    infos: Dict[Tuple[str, str], List[_ClassInfo]] = {}
    for scanned, is_package, tree in entries:
        # the names a file's own imports and classes are looked up by: as scanned, or as the package names them
        module = scanned if plain else (f"{prefix}.{scanned}" if scanned else prefix)
        imports = _imports_in(tree, module, is_package)
        for node in ast.walk(tree):
            if not isinstance(node, ast.ClassDef):
                continue
            bases = [_base_ref(base, module, imports) for base in node.bases]
            members = set()
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    members.add(item.name)
                elif isinstance(item, ast.Assign):
                    members |= {t.id for t in item.targets if isinstance(t, ast.Name)}
                elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    members.add(item.target.id)
            for sub in ast.walk(node):
                if isinstance(sub, ast.Attribute) and isinstance(sub.ctx, ast.Store) and _root_name(sub) == "self":
                    members.add(sub.attr)
            info = _ClassInfo(node.name, root, bases, members, "__getattr__" in members)
            names = [(module, node.name)]
            if plain and prefix:
                names.append((f"{prefix}.{module}" if module else prefix, node.name))
            for key in names:
                infos.setdefault(key, []).append(info)
    return infos


def _find(infos, ref: ClassRef) -> List[_ClassInfo]:
    """The classes a reference names, by the module the import names (`cairnml.session.Session`)."""
    if ref is None:
        return []
    return infos.get(ref, [])


def _session_members(infos) -> Optional[Tuple[Set[str], bool, List[str]]]:
    """The members of the Session classes under the root and of the classes that derive from them, with what those
    inherit; None when no Session class is defined under the root."""
    unique = list({id(info): info for group in infos.values() for info in group}.values())
    family = [info for info in unique if info.root and info.name == "Session"]
    if not family:
        return None
    members_of = {id(info) for info in family}
    grew = True
    while grew:  # a class of the root that derives from a member is a session too (a test's fake session)
        grew = False
        for info in unique:
            if not info.root or id(info) in members_of:
                continue
            if any(id(found) in members_of for ref, _ in info.bases for found in _find(infos, ref)):
                family.append(info)
                members_of.add(id(info))
                grew = True
    members: Set[str] = set()
    dynamic = False
    unknown: List[str] = []
    pending, seen = list(family), set()
    while pending:
        info = pending.pop()
        if id(info) in seen:
            continue
        seen.add(id(info))
        members |= info.members
        dynamic = dynamic or info.dynamic
        for ref, written in info.bases:
            found = _find(infos, ref)
            if found:
                pending += found
            elif written not in TRIVIAL_BASES:
                unknown.append(written)
    return members, dynamic, sorted(set(unknown))


BATCH_KEYWORDS = ("requests", "validate_requests", "allow_raw_requests")


class _Visitor(ast.NodeVisitor):
    def __init__(
        self,
        path,
        schema,
        generated,
        allow,
        findings,
        used,
        version_literals,
        module_scope,
        class_names,
        sessions,
        test_file=False,
    ):
        self.path, self.schema, self.allow, self.findings, self.used = path, schema, allow, findings, used
        self.version_literals = version_literals  # False for a generated module: it is the one place versions live
        self.hand_written = version_literals  # the generated modules are not judged for calls by name either
        self.test_file = test_file  # a version string in a test is data unless it picks a request's version
        self.picking: Set[int] = set()  # the constants that are the value of a `version=` keyword
        self.data: Set[int] = set()  # the constants in an assertion or a comparison of a test
        self.scopes = [module_scope]  # what the names bound in each enclosing scope are (see _bindings)
        self.class_names, self.sessions = class_names, sessions  # sessions: the calls are collected, not judged
        self.session_calls: List[Tuple[ast.AST, str, str]] = []
        self.not_api_versions: Set[int] = set()  # literals that are not judged: a server version is not an API version
        self.aliases: Dict[str, str] = {}  # local name -> generated service
        self.requests = {
            service: {camel(a) + "Request": a for a in schema[service].actions}
            for service in generated
            if service in schema
        }

    def report(self, node, message):
        self.findings.append(Finding(self.path, node.lineno, message))

    def visit_ImportFrom(self, node):
        if node.module and node.module.split(".")[-1] == "services":
            for alias in node.names:
                if alias.name in self.requests:
                    self.aliases[alias.asname or alias.name] = alias.name
        self.generic_visit(node)

    def _mark_data(self, node):
        if self.test_file:
            self.data |= {id(sub) for sub in ast.walk(node) if isinstance(sub, ast.Constant)}

    def visit_Assert(self, node):
        self._mark_data(node)
        self.generic_visit(node)

    def visit_Compare(self, node):
        self._mark_data(node)
        self.generic_visit(node)

    def _is_api_version(self, node, text) -> bool:
        if not (VERSION_LITERAL.match(text) or VERSION_IN_URL.search(text)):
            return False
        if not self.test_file:
            return True
        return id(node) not in self.data and (id(node) in self.picking or VERSION_IN_URL.search(text) is not None)

    def visit_Constant(self, node):
        text = _string(node)
        if id(node) in self.not_api_versions:
            return
        if text is not None and self.version_literals and self._is_api_version(node, text):
            self.report(
                node, f"{text!r} is an API version written in hand-written code: take it from the generated classes"
            )

    def visit_Call(self, node):
        if _call_name(node.func) == "check_min_server_version":
            self.not_api_versions |= {id(arg) for arg in node.args}
        self.picking |= {id(keyword.value) for keyword in node.keywords if keyword.arg == "version"}
        self.generic_visit(node)
        func = node.func
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name) and func.value.id in self.aliases:
            self._request_class(node, self.aliases[func.value.id], func.attr)
        if isinstance(func, ast.Attribute) and func.attr in SESSION_SENDERS and self.hand_written:
            self._call_by_name(node, func.attr)
        if isinstance(func, ast.Attribute) and self.sessions and self._is_session(func.value):
            self.session_calls.append((node, ast.unparse(func.value), func.attr))
        keywords = {k.arg: _string(k.value) for k in node.keywords if k.arg}
        if keywords.get("service") and keywords.get("action"):
            self._named_call(node, keywords["service"], keywords["action"], keywords.get("version"))

    def visit_FunctionDef(self, node):
        self.scopes.append(_bindings([node], self.class_names))
        self.generic_visit(node)
        self.scopes.pop()

    visit_AsyncFunctionDef = visit_FunctionDef

    def _is_session(self, node) -> bool:
        if isinstance(node, ast.Name):
            for scope in reversed(self.scopes):
                if node.id in scope:
                    return scope[node.id] == SESSION
            return node.id in SESSION_NAMES
        return isinstance(node, ast.Attribute) and node.attr in SESSION_NAMES

    def _request_class(self, node, service, class_name):
        if not class_name.endswith("Request"):
            return
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", class_name[: -len("Request")]).lower()
        if f"{service}.{snake}" in self.allow.exempt:
            self.used.add(f"{service}.{snake}")
        action = self.requests[service].get(class_name)
        if action is None:
            if f"{service}.{snake}" not in self.allow.exempt:
                self.report(node, f"{service}.{snake} is not in the schema ({service}.{class_name})")
            return
        described = self.schema[service].actions[action]
        request = described.request or {}
        if described.batch_request:
            known = set(BATCH_KEYWORDS)  # the batch base class takes these, not the fields of an action
        elif any(key in request for key in ("anyOf", "oneOf", "allOf")):
            return  # the request is one of several shapes: the generated class does not list its fields
        else:
            # a field is named in Python as the generator names it: a character that is not in an identifier is "_"
            known = {re.sub(r"\W", "_", name) for name in (request.get("properties") or {})}
        for keyword in node.keywords:
            # underscore names are the base class's own options (for example _allow_extra_fields_)
            if keyword.arg and not keyword.arg.startswith("_") and keyword.arg not in known:
                self.report(node, f"{service}.{action} has no field `{keyword.arg}`")

    def _call_by_name(self, node, method):
        """A call whose service and action are strings. For an action of the schema the request class of that action
        is the way to send it. A call that gives both by keyword and names an action the schema lacks is left to
        `_named_call`; a call with positional arguments is reported here, since `_named_call` does not read them. The
        positional form is judged only when the service is in the schema, or the method is `send_request` whose first
        two parameters are the service and the action (`dict.get("a", "b")` is not a call of the API)."""
        keywords = {k.arg: k.value for k in node.keywords if k.arg}
        positional = node.args
        service = _string(keywords.get("service", positional[0] if len(positional) > 0 else None))
        action = _string(keywords.get("action", positional[1] if len(positional) > 1 else None))
        if not service or not action:
            return
        full = f"{service}.{action}"
        if full in self.allow.exempt:
            self.used.add(full)
            return
        if service in self.schema and action in self.schema[service].actions:
            request_class = f"{service}.{camel(action)}Request"
            self.report(node, f"{method} names {full} by strings: build {request_class} and send it instead")
        elif not ("service" in keywords and "action" in keywords) and (
            method == "send_request" or service in self.schema
        ):
            self.report(node, f"{full} is not in the schema")

    def _named_call(self, node, service, action, version):
        full = f"{service}.{action}"
        if full in self.allow.exempt:
            self.used.add(full)
            return
        found = self.schema[service].actions.get(action) if service in self.schema else None
        if found is None:
            self.report(node, f"{full} is not in the schema")
        elif version is not None and version not in found.versions:
            self.report(node, f"{version} is not a version of {full} (declared: {', '.join(found.versions)})")


def _folder_prefix(folder: Path) -> str:
    """The package name of a folder (`cairnml` for the SDK's package folder), which an import names it by."""
    return "" if Path(folder).is_file() else Path(folder).name


def _parse_folder(folder: Path) -> List[Tuple[Path, str, ast.Module, str, bool, Path]]:
    """Every Python file under the folder (or the file): path, text, tree, module name, is-package, and the folder."""
    folder = Path(folder)
    paths = [folder] if folder.is_file() else sorted(folder.rglob("*.py"))
    parsed = []
    for path in paths:
        text = path.read_text()
        module, is_package = _module_name(path, folder)
        parsed.append((path, text, ast.parse(text, filename=str(path)), module, is_package, folder))
    return parsed


def check_callers(
    root: Path,
    schema: Dict[str, Service],
    generated: Set[str],
    allow: Allow,
    sessions: bool = False,
    bases: Sequence[Path] = (),
) -> List[Finding]:
    root = Path(root)
    parsed = _parse_folder(root)
    findings: List[Finding] = []
    used: Set[str] = set()
    session_calls = []
    members = None
    if sessions:
        infos = _class_index(
            [(module, package, tree) for _, _, tree, module, package, _ in parsed],
            root=True,
            prefix=_folder_prefix(root),
            plain=True,
        )
        for base in bases:
            base_entries = [(module, package, tree) for _, _, tree, module, package, _ in _parse_folder(base)]
            for key, group in _class_index(base_entries, root=False, prefix=_folder_prefix(base), plain=False).items():
                infos.setdefault(key, []).extend(group)
        members = _session_members(infos)
    for path, text, tree, _, _, folder in parsed:
        class_names = _session_names_in(tree)
        module_level = [
            s for s in tree.body if not isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        ]
        visitor = _Visitor(
            path,
            schema,
            set(generated),
            allow,
            findings,
            used,
            version_literals=not any(line.startswith(GENERATED_PREFIX) for line in text.splitlines()),
            module_scope=_bindings(module_level, class_names),
            class_names=class_names,
            sessions=sessions,
            test_file=_is_test_file(path, folder),
        )
        visitor.visit(tree)
        session_calls += [(path, node, receiver, method) for node, receiver, method in visitor.session_calls]
    if sessions:
        findings += _session_findings(root, members, session_calls)
    for key in sorted(set(allow.exempt) - used):
        findings.append(Finding(Path(allow.source), 1, f"exempt {key} no longer matches any call: remove it"))
    return findings


def _session_findings(root: Path, members, session_calls) -> List[Finding]:
    if members is None:
        if session_calls:
            path, node, receiver, method = session_calls[0]
            return [
                Finding(
                    path,
                    node.lineno,
                    f"{receiver}.{method} cannot be checked: no class Session is defined under {root}",
                )
            ]
        return []
    known, dynamic, unknown = members
    if unknown:
        if session_calls:
            return [
                Finding(
                    root,
                    1,
                    f"Session inherits from {', '.join(unknown)}, which is not defined under the root: "
                    "its methods cannot be checked",
                )
            ]
        return []
    if dynamic:
        return []
    findings = []
    for path, node, receiver, method in session_calls:
        if method not in known and method not in HTTP_SESSION_METHODS and not hasattr(object, method):
            findings.append(Finding(path, node.lineno, f"{receiver}.{method} is not a method of the Session class"))
    return findings
